/**
 * Generates the static geography used by the /map layer.
 *
 *   shared/worldGeo.ts          Natural Earth 110m country outlines, projected
 *                               with a cropped Miller cylindrical projection
 *   shared/countries.generated.ts  ISO metadata (code, name, region, centroid)
 *
 * Both files are committed so the app has zero runtime geo dependencies and
 * works fully offline. Re-run with `npm run generate:world` after upgrading
 * world-atlas / world-countries.
 */
import { createRequire } from 'node:module'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { feature } from 'topojson-client'

const require = createRequire(import.meta.url)
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const WIDTH = 1000
const HEIGHT = 420
const LAT_TOP = 84
const LAT_BOTTOM = -58
const RAD = Math.PI / 180

function millerY(lat) {
  const phi = Math.max(LAT_BOTTOM, Math.min(LAT_TOP, lat)) * RAD
  return Math.log(Math.tan(Math.PI / 4 + 0.4 * phi))
}

const Y_TOP = millerY(LAT_TOP)
const Y_BOTTOM = millerY(LAT_BOTTOM)

function project([lon, lat]) {
  const x = ((lon + 180) / 360) * WIDTH
  const y = ((millerY(lat) - Y_TOP) / (Y_BOTTOM - Y_TOP)) * HEIGHT
  return [x, y]
}

function ringToPath(ring) {
  let d = ''
  let prevX = null
  let prevY = null
  for (let i = 0; i < ring.length; i++) {
    const [x, y] = project(ring[i])
    const rx = Math.round(x * 10) / 10
    const ry = Math.round(y * 10) / 10
    if (rx === prevX && ry === prevY) continue
    d += `${d ? 'L' : 'M'}${rx} ${ry}`
    prevX = rx
    prevY = ry
  }
  return d ? `${d}Z` : ''
}

function geometryToPath(geometry) {
  if (!geometry) return ''
  if (geometry.type === 'Polygon') {
    return geometry.coordinates.map(ringToPath).filter(Boolean).join('')
  }
  if (geometry.type === 'MultiPolygon') {
    return geometry.coordinates
      .map(poly => poly.map(ringToPath).filter(Boolean).join(''))
      .filter(Boolean)
      .join('')
  }
  return ''
}

const topology = require('world-atlas/countries-110m.json')
const countriesMeta = require('world-countries')

const byNumeric = new Map()
for (const country of countriesMeta) {
  if (country.ccn3) byNumeric.set(country.ccn3, country)
}

const features = feature(topology, topology.objects.countries).features
const world = []

for (const item of features) {
  const numeric = String(item.id ?? '')
  if (numeric === '010') continue // Antarctica — cropped out of the projection.
  const meta = byNumeric.get(numeric)
  const path = geometryToPath(item.geometry)
  if (!path) continue
  world.push({
    id: numeric,
    code: meta?.cca2 ?? null,
    name: meta?.name.common ?? item.properties?.name ?? 'Unknown',
    path
  })
}

world.sort((a, b) => a.name.localeCompare(b.name))

const worldFile = `/* AUTO-GENERATED by scripts/generate-geo.mjs — do not edit by hand.
 * Natural Earth 110m country outlines (public domain, via world-atlas),
 * projected with a cropped Miller cylindrical projection. */

export interface WorldCountry {
  /** ISO 3166-1 numeric code (matches world-atlas feature ids). */
  id: string
  /** ISO 3166-1 alpha-2 code, when known. */
  code: string | null
  /** Common English country name. */
  name: string
  /** SVG path data in a ${WIDTH}×${HEIGHT} viewBox. */
  path: string
}

export const WORLD_WIDTH = ${WIDTH}
export const WORLD_HEIGHT = ${HEIGHT}

export const WORLD_COUNTRIES: WorldCountry[] = ${JSON.stringify(world, null, 0)}

/** Equirectangular (Miller-cropped) projection for camera coordinates. */
export function projectLon(lon: number): number {
  return Math.min(WORLD_WIDTH, Math.max(0, ((lon + 180) / 360) * WORLD_WIDTH))
}

export function projectLat(lat: number): number {
  const clamped = Math.max(${LAT_BOTTOM}, Math.min(${LAT_TOP}, lat)) * (Math.PI / 180)
  const y = Math.log(Math.tan(Math.PI / 4 + 0.4 * clamped))
  const top = Math.log(Math.tan(Math.PI / 4 + 0.4 * ${LAT_TOP} * (Math.PI / 180)))
  const bottom = Math.log(Math.tan(Math.PI / 4 + 0.4 * ${LAT_BOTTOM} * (Math.PI / 180)))
  const projected = ((y - top) / (bottom - top)) * WORLD_HEIGHT
  // Normalise -0 so SVG attributes never render as "-0".
  return Math.min(WORLD_HEIGHT, Math.max(0, projected)) || 0
}
`

const countries = countriesMeta
  .map(c => ({
    code: c.cca2,
    numeric: c.ccn3 ?? '',
    name: c.name.common,
    official: c.name.official,
    region: c.region || '',
    subregion: c.subregion || '',
    lat: Array.isArray(c.latlng) ? Math.round(c.latlng[0] * 1000) / 1000 : 0,
    lon: Array.isArray(c.latlng) ? Math.round(c.latlng[1] * 1000) / 1000 : 0
  }))
  .sort((a, b) => a.name.localeCompare(b.name))

const countriesFile = `/* AUTO-GENERATED by scripts/generate-geo.mjs — do not edit by hand.
 * ISO 3166 metadata derived from world-countries (ODbL). */

export interface CountryMeta {
  code: string
  numeric: string
  name: string
  official: string
  region: string
  subregion: string
  lat: number
  lon: number
}

export const COUNTRIES: CountryMeta[] = ${JSON.stringify(countries, null, 0)}
`

mkdirSync(resolve(root, 'shared'), { recursive: true })
writeFileSync(resolve(root, 'shared/worldGeo.ts'), worldFile)
writeFileSync(resolve(root, 'shared/countries.generated.ts'), countriesFile)

console.log(`worldGeo.ts: ${world.length} countries, ${(worldFile.length / 1024).toFixed(1)} KiB`)
console.log(`countries.generated.ts: ${countries.length} entries, ${(countriesFile.length / 1024).toFixed(1)} KiB`)
